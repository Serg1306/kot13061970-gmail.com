const DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

// Дата рождения для разбора: настоящая дата, не раньше 1930 года и не в будущем.
export function validBirth(s) {
  const m = DATE_RE.exec(typeof s === 'string' ? s : '');
  if (!m) return false;
  const d = new Date(Date.UTC(+m[1], +m[2] - 1, +m[3]));
  return d.getUTCFullYear() === +m[1] && d.getUTCMonth() === +m[2] - 1 && +m[1] >= 1930 && d.getTime() <= Date.now();
}

