const digitSum = n => String(n).split('').reduce((a, c) => a + +c, 0);
const reduce9 = n => { while (n > 9) n = digitSum(n); return n; };
const famOf = n => reduce9(n === 11 ? 2 : n === 22 ? 4 : n);
function eastRelation(a, b) {
  const d = Math.abs(a.i - b.i);
  if (d === 6) return 'clash';
  if (a.i === b.i) return 'same';
  if (a.i % 4 === b.i % 4) return 'allies';
  if ((a.i + b.i) % 12 === 1) return 'friends';
  return 'neutral';
}
const fmt = d => d.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', weekday: 'long', timeZone: 'UTC' });

// Удачные даты: число дня (сумма цифр даты) совпадает с числом судьбы одного из вас или с числом пары.
function luckyDates(n1, n2, from = Date.now(), days = 45, max = 5) {
  const pairNum = reduce9(famOf(n1) + famOf(n2));
  const want = new Map([[famOf(n1), 'ваше число дня'], [famOf(n2), 'число дня партнёра'], [pairNum, 'число вашей пары']]);
  const out = [];
  const start = new Date(from); start.setUTCHours(0, 0, 0, 0);
  for (let i = 1; i <= days && out.length < max; i++) {
    const d = new Date(start.getTime() + i * 864e5);
    const day = reduce9(digitSum(`${d.getUTCDate()}${d.getUTCMonth() + 1}${d.getUTCFullYear()}`));
    if (want.has(day)) out.push({ date: d.toISOString().slice(0, 10), title: fmt(d), why: `${want.get(day)} (${day})` });
  }
  return { pairNum, dates: out };
}

